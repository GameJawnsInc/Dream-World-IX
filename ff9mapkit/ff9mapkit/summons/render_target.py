@dataclass(frozen=True)
class Route:
    """One 15bpp page key the census saw read in one container, and what it sampled."""
    page: Tuple[int, int]
    kind: str
    renders: int
    frames: Tuple[int, int]

    def covers(self, cell: Tuple[int, int]) -> bool:
        return (self.page[0] <= cell[0] < self.page[0] + PAGE_SPAN
                and self.page[1] == cell[1] - cell[1] % PAGE_LINES)

    def describe(self) -> str:
        return ("the 15bpp page (%d,%d) read %s on %d mesh render(s), f%d-%d"
                % (self.page[0], self.page[1], KIND_TEXT.get(self.kind, self.kind), self.renders,
                   self.frames[0], self.frames[1]))


@dataclass(frozen=True)
class Feed:
    """One VRAM cell whose fragments drew the render target, at the depth it was read."""
    cell: Tuple[int, int]
    bpp: int
    pixels: int
    frames: int
    #: the CLUT cells the drawing keys read these bytes through, LOWEST ADDRESS FIRST (the class-C
    #: display rule), each with its fragments -- :data:`_FEED_CLUT_ROWS`
    cluts: Tuple[Tuple[Tuple[int, int], int], ...] = ()

    def describe(self, total: int = 0) -> str:
        share = (" (%d%% of the target's fragments)" % round(100.0 * self.pixels / total)
                 if total else "")
        return "x%d_y%d at %dbpp%s" % (self.cell[0], self.cell[1], self.bpp, share)


def _routes() -> Dict[int, Tuple[Route, ...]]:
    out: Dict[int, list] = {}
    for ef, x, y, kind, n, f0, f1 in _ROUTE_ROWS:
        out.setdefault(ef, []).append(Route(page=(x, y), kind=kind, renders=n, frames=(f0, f1)))
    return {ef: tuple(v) for ef, v in out.items()}


def _feeds() -> Dict[int, Tuple[Feed, ...]]:
    split: Dict[Tuple[int, int, int, int], list] = {}
    for ef, x, y, bpp, cx, cy, px in _FEED_CLUT_ROWS:
        split.setdefault((ef, x, y, bpp), []).append(((cx, cy), px))
    out: Dict[int, list] = {}
    for ef, x, y, bpp, px, n in _FEED_ROWS:
        out.setdefault(ef, []).append(Feed(cell=(x, y), bpp=bpp, pixels=px, frames=n,
                                           cluts=tuple(sorted(split.get((ef, x, y, bpp), ()),
                                                              key=lambda c: (c[0][1], c[0][0])))))
    return {ef: tuple(sorted(v, key=lambda f: (-f.pixels, f.cell, f.bpp))) for ef, v in out.items()}


#: ``{effect: (Route, ...)}`` / ``{effect: (Feed, ...)}`` (largest feeder first) / ``{effect: frame}``.
ROUTES: Dict[int, Tuple[Route, ...]] = _routes()
FEEDS: Dict[int, Tuple[Feed, ...]] = _feeds()
TARGETS: Dict[int, int] = {ef: f for ef, f in _TARGET_ROWS}


def routes(effect: Optional[int]) -> Tuple[Route, ...]:
    """Every 15bpp page key the census saw one container read. ``()`` for an unknown effect."""
    return ROUTES.get(int(effect), ()) if effect is not None else ()


def feeders(effect: Optional[int]) -> Tuple[Feed, ...]:
    """The VRAM cells that drew this container's render target, largest first."""
    return FEEDS.get(int(effect), ()) if effect is not None else ()


def target_from(effect: Optional[int]) -> Optional[int]:
    """The first frame on which the container's target exists, or None if it never renders one."""
    return TARGETS.get(int(effect)) if effect is not None else None


@dataclass(frozen=True)
class CellRoute:
    """What every 15bpp read covering one cell sampled, in one container -- the measured verdict."""
    effect: Optional[int]
    cell: Tuple[int, int]
    verdict: str
    reads: Tuple[Route, ...]
    target_from: Optional[int]
    #: this cell's OWN bytes, read into the target at 4/8 bpp -- the only way a repaint here reaches
    #: the screen once the 15bpp reads have gone to the target, and then as palette indices.
    own_feeds: Tuple[Feed, ...]
    #: every cell that drew the target, largest first: what a NEVER_VRAM read actually shows.
    feeders: Tuple[Feed, ...]

    @property
    def never_vram(self) -> bool:
        return self.verdict == NEVER_VRAM

    def describe(self) -> str:
        """The measurement, in the sentence a refusal or disclosure quotes."""
        if self.verdict == UNMEASURED:
            return ("UNMEASURED: no routes census covers this effect, so the kit cannot say what a 15bpp "
                    "read of this cell samples")
        if self.verdict == UNPORTED_VERDICT:
            return ("UNPORTED: the headless port does not model this effect's special-cased textures "
                    "(Memoria hard-codes a screenshot, blur or custom texture for it), so the census says "
                    "nothing either way about its 15bpp reads")
        if self.verdict == UNREAD:
            return ("UNREAD: the census ran this effect and saw no 15bpp read of a page covering this "
                    "cell -- %s.  Not observed is not safe: the host stands actors at the origin with "
                    "no battle camera" % ("it never renders into a target, so at Battle Speed < 3 a read "
                                          "would sample VRAM" if self.target_from is None else
                                          "its target exists from f%d, and a read after that samples "
                                          "the target" % self.target_from))
        reads = "; ".join(r.describe() for r in self.reads)
        if self.verdict == READS_VRAM:
            return "READS_VRAM: every 15bpp read covering this cell sampled VRAM (%s)" % reads
        if self.verdict == MIXED:
            return ("MIXED: some 15bpp reads covering this cell sampled VRAM and some did not, so a "
                    "repaint shows only on the VRAM reads' frames (%s)" % reads)
        return ("NEVER_VRAM: every 15bpp read of a page covering this cell sampled something other than "
                "VRAM -- %s%s" % (reads, "; this effect's target exists from f%d" % self.target_from
                                  if self.target_from is not None else ""))

    def own_feed_line(self) -> str:
        """Whether THIS cell's bytes reach the screen at all, by the only other road there is."""
        if not self.never_vram:
            return ""
        if not self.own_feeds:
            return ("no draw of the target reads this cell at any depth either, and the kit names no "
                    "reader of it at another depth, so no measured road takes a repaint here to the "
                    "screen")
        total = sum(f.pixels for f in self.feeders)
        return ("this cell's OWN bytes do feed the target, read at %s -- so a repaint here reaches the "
                "screen through the target, decoded as palette indices, not as the colours you painted "
                "(ef446's cast showed cyan 15bpp bands as a salmon checker this way)"
                % " and ".join("%dbpp (%d%% of the target's fragments)"
                               % (f.bpp, round(100.0 * f.pixels / total)) for f in self.own_feeds))


def cell_route(effect: Optional[int], cell: Tuple[int, int]) -> CellRoute:
    """The measured verdict for one cell's 15bpp reads in one container (:data:`VERDICTS`)."""
    cell = (int(cell[0]), int(cell[1]))
    rd = tuple(r for r in routes(effect) if r.covers(cell))
    fd = feeders(effect)
    own = tuple(f for f in fd if f.cell == cell)
    t0 = target_from(effect)
    if effect is None or int(effect) not in CENSUS_IDS:
        verdict = UNMEASURED
    elif int(effect) in UNPORTED:
        verdict = UNPORTED_VERDICT
    elif not rd:
        verdict = UNREAD
    else:
        vram = {r.kind == "IMAGE" for r in rd}
        verdict = READS_VRAM if vram == {True} else NEVER_VRAM if vram == {False} else MIXED
    return CellRoute(effect=effect, cell=cell, verdict=verdict, reads=rd, target_from=t0,
                     own_feeds=own, feeders=fd)


@dataclass(frozen=True)
class DrawnDepth:
    """CHANNEL D -- what the census saw DRAW one cell into the render target: every depth it was read
    at, and every CLUT each depth was read through.

    The strongest depth evidence this lane has, and the narrowest: the depth is the drawing
    primitive's own tpage mode off the plugin's executed stream -- a draw, not a binding and not a
    registration -- but only draws INTO the target are recorded (:data:`DRAWN_CAVEAT`).
    """
    effect: int
    cell: Tuple[int, int]
    #: one :class:`Feed` per depth the cell was drawn at, shallowest first
    feeds: Tuple[Feed, ...]

    @property
    def depths(self) -> Tuple[int, ...]:
        return tuple(f.bpp for f in self.feeds)

    @property
    def dual(self) -> bool:
        """Drawn at two depths -- the same bytes as two pictures.  A hazard, not a vote."""
        return len(self.feeds) > 1

    @property
    def bpp(self) -> Optional[int]:
        return self.feeds[0].bpp if not self.dual else None

    @property
    def clut_cells(self) -> Tuple[Tuple[int, int], ...]:
        """The CLUT cells of a single-depth draw, display binding (lowest address) first."""
        return tuple(c for c, _n in self.feeds[0].cluts) if not self.dual else ()

    def evidence(self) -> str:
        """The measurement, in the sentence a refusal or disclosure quotes."""
        return ("the headless routes census saw this cell DRAWN into the render target at %s"
                % " AND ".join("%dbpp (%d fragments over %d frames, through %s)"
                               % (f.bpp, f.pixels, f.frames,
                                  ", ".join("CLUT x%d_y%d" % c for c, _n in f.cluts) or "no CLUT")
                               for f in self.feeds))


def drawn_depth(effect: Optional[int], cell: Tuple[int, int]) -> Optional[DrawnDepth]:
    """CHANNEL D for one cell, or ``None`` where no draw of the target read it."""
    cell = (int(cell[0]), int(cell[1]))
    fs = tuple(sorted((f for f in feeders(effect) if f.cell == cell), key=lambda f: f.bpp))
    return DrawnDepth(effect=int(effect), cell=cell, feeds=fs) if fs else None


