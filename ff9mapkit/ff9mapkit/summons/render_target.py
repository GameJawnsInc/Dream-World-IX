r"""THE RENDER-TARGET ROUTE -- a 15bpp read that never samples VRAM.

WHAT DECIDES IT (Memoria ``Global/SFXMesh/SFXMesh.cs``, ``GetTexture``). A textured mesh whose key is
direct colour (texture mode 2, "15bpp") is handed VRAM only as the LAST resort. In order:

1. its page origin is left of x = 384 (``SFXKey.IsBlurTexture``, ``SFXKey.cs:82``) -> the BLUR texture,
   the previous frame's screen;
2. its page is ``PSXTextureMgr.bgKey`` -> the battle-ground capture;
3. four hard-coded keys: Devour's crop of the blur texture, Slow's and Silent Voice's screenshots, and
   Stop's (448,256), which alone reads VRAM;
4. the effect has rendered into its DR_AREA target -- ``PSXTextureMgr.isCreateGenTexture``, set by
   ``SFXRenderTextureEnd`` and cleared only by ``PSXTextureMgr.Reset`` when the next cast starts ->
   the 512x256 TARGET (VRAM x 384-895, y 256-511, by position);
5. otherwise -> VRAM.

WHY THE TEXEL LANE HAS TO KNOW
------------------------------
**Once an effect has drawn into its target, no 15bpp read in it samples VRAM again.** A ``direct15``
repaint there is byte-correct on disk, deploys, verifies -- and no 15bpp read ever samples it. What
those reads show is what the program DREW into the target, with indexed primitives, from other cells.
The bytes can still reach the screen through a 4 or 8 bpp read of the same bytes, and then as palette
INDICES, not as the colours that were painted. The census measures those reads where they draw INTO the
target (:attr:`CellRoute.own_feeds`); a 4/8 bpp read straight to the screen is not in this table, and the
kit's own derivation names no such reader on any cell it hands out at 15bpp (a cell read at two depths
is refused). Both outcomes are this lane's silent failure: the first shows nothing, the second shows
something that is not the picture, and either null gets charged to whatever the cast was testing.

THE MEASUREMENT (``studies/custom-summons/headless/raster.py routes``: the user's own plugin run headless
over all 372 containers, 0 errors). **66 containers render into the target.** Of the 181 (container,
page) pairs read at 15bpp, 70 read the target, 88 the blur texture, 13 the ground capture and 10 VRAM
(Stop's hard-coded page, Carbuncle's four gem variants read before -- or without -- a target, a
reserved depth-3 page, and four rows on three effects the port does not model, :data:`UNPORTED`).
Against the texel edit surface (:data:`SURFACE_15BPP`): **every one of the 22 default-surface 15bpp
cells reads NEVER_VRAM**, and so do 79 of the 87 reachable with every acknowledgement. The cast record
agrees three times out of three (:data:`CASTS`).

THE TWO CAST PATHS. At Battle Speed < 3 a cast runs live through ``SFXDataMesh.Runtime`` -- the path the
headless host ports, and the one the census measures. At Speed >= 3 (``UseCamera`` false,
``UnifiedBattleSequencer.cs:345``) Memoria pre-records it through ``SFXData.LoadSFXRawLoop``, which sets
``isCreateGenTexture`` after EVERY frame (``SFXData.cs:403``), so from the second frame even an effect
that never renders a target routes its 15bpp reads to it. That only widens rule 4: a NEVER_VRAM verdict
holds on both paths, and a READS_VRAM or UNREAD one holds only at Speed < 3 (:data:`SPEED_CAVEAT`).

THE JOIN, AND ITS COARSENESS
----------------------------
A 15bpp page spans 256 halfwords (four 64-wide columns) and 256 lines, and the route is decided per KEY,
not per texel -- so a page routed to the target routes EVERY texel it could sample there, and the
cell-level verdict is exact in that direction. A cell is joined to every census page whose span covers
it. The other direction is coarser: a page routed to VRAM is not proof that THIS cell's texels are ever
sampled, only that a 15bpp read of its page could see them.

CHANNEL D -- THE DEPTH A CELL IS DRAWN AT
----------------------------------------
The remedy names what the target is DRAWN from, and on 20 of the 22 refusals those cells were ones the
static derivation gives no depth to (``depth-unknown``) or calls readerless (``displaced``) -- so it named
nothing an author could paint. But the census MEASURES each feeder: the depth the drawing primitive's own
tpage mode reads it at, and (a second run, ``_FEED_CLUT_ROWS``) the CLUT each fragment was read through.
:func:`drawn_depth` is that measurement per cell, and ``repaint`` consults it as the depth channel
``"drawn"``: a refusal states it, and behind :data:`DRAWN_ACK_KEY` + ``expect_bpp`` the cell is handed out
at that depth, keyed by the lowest-addressed CLUT the draw used. A cell drawn at two depths is a hazard and
never emits. Calibrated before it was trusted (``studies/custom-summons/tier-w/drawn_gates.py`` D2): where
the static derivation also speaks the depths agree on 13 cells and differ on 6 -- five of them a 15bpp
reader that never reads VRAM over bytes the draw reads at 8bpp, the sixth a channel-G column bound at 4
that the draw reads at 8 (ef499 ``x704_y384``). With the key the remedy names a paintable feeder on 14 of
the 22 (:data:`SURFACE_15BPP_KEYED_REMEDY`), and headless a repaint of one reaches the screen through the
target. What it cannot see is :data:`DRAWN_CAVEAT`.

WHY THIS IS A CACHED CONSTANT, AND WHAT PINS IT
-----------------------------------------------
The measurement needs the plugin DLL from the user's install and the stock containers, so -- like
:data:`ff9mapkit.summons.scroll_blit.REFRESH` -- this table is a CACHE OF A MEASUREMENT and is
re-derivation-pinned: ``studies/custom-summons/tier-w/render_target_gates.py`` reads the census again
and asserts equality row for row, re-runs the kit's own join over the corpus, checks the falsifier fired
(ef429 with its target suppressed reads its 15bpp page from VRAM), and retrodicts the three casts. The
counts are asserted AT IMPORT so a truncated table fails loudly.

PROVENANCE
----------
Effect ids, VRAM coordinates, depths, frame numbers and counts. No stock byte, no hex run.
"""
