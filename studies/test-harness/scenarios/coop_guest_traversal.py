class Ctx:
    def __init__(self, mode: str, has_key: bool):
        self.mode = mode
        self.has_key = has_key
        self.table, self.table_why = None, ""
        self.marks: dict = {}            # a predicted leg -> its press record (K-CAL-M)
        self.lever_held = False          # a lever held INTO the release (K-R then expects its line)
        self.trips0 = None               # trips.total at K2 (K-TRIPS)
        self.dress_noted = False
        self.k0_ok = False
        self.k3: list = []              # (field, ok, why) per arrival -- K3 is ONE row (the tally), judged over all of them


def _ns(g, sub: str, *args) -> tuple:
    return cb.try_ns(g, sub, *args)


def gl_op(g, ctx: Ctx, op: str, *args) -> tuple:
    """`netsync guestlocal <op>` -- NEVER sent to an engine without the key (the driver refuses it there too)."""
    if not ctx.has_key:
        return False, "this engine publishes no `netsync.guestlocal` (s156): never sent"
    return _ns(g, "guestlocal", op, *args)


def rest(g, timeout: float = REST_S):
    """A field at rest: control, no window, no fade -- then settled (the position a judgement reads)."""
    cb.poll(g, cb.free, timeout, "the field at rest (control, no window, no fade)")
    try:
        return g.settle(timeout=3.0)
    except (HarnessError, TypeError):
        return g.state


def set_bench(g, on: bool) -> tuple:
    """`netsync bench 1|0` AT REST (THE ORDERING LAW 5), read back."""
    rest(g)
    ok, why = _ns(g, "bench", 1 if on else 0)
    st = cb.poll(g, lambda s: (s.netsync or {}).get("bench") is on, 3.0, f"bench {int(on)} read back")
    return ok and st is not None, why or ("" if st is not None else f"bench never read {on}")


def go_to(g, fid: int, xz, region=None) -> tuple:
    """route_to (x, z) on the field's walkmesh, keeping out of every gateway polygon; (ok, why). ``region`` -- the press
    polygon the stand must lie in."""
    avoid = [list(p) for p in GEOM[fid]["gateways"].values()]
    try:
        g.route_to(float(xz[0]), float(xz[1]), avoid=avoid, tolerance=ROUTE_TOL, timeout=ROUTE_S,
                   clearance=GEOM[fid].get("clearance"))   # None = route_to's own (cam.COLLISION_RADIUS_W, 80 u)
    except HarnessError as err:
        return False, f"route_to {tuple(xz)} raised: {str(err)[:200]}"
    st = rest(g)
    p = pos(st)
    if region is not None:
        ok = p is not None and in_quad(p[0], p[2], region)
    else:
        ok = dist_xz(p, xz) <= ROUTE_TOL + 15
    return ok, f"at {_fmt(p)} after route_to {tuple(xz)}" + ("" if ok else " -- NOT in place")


def _release_all(g) -> None:
    for b in ("up", "down"):
        try:
            g.release(b)
        except HarnessError:
            pass


def close_line(g) -> bool:
    """Page out the window a relayed talk opened -- Confirm ONLY while a window is open (a stray Confirm at rest inside
    e9 would press the ladder)."""
    cb.poll(g, lambda s: s.dialog_open, 2.0, "the talk's window")
    for _ in range(12):
        if not g.state.dialog_open:
            break
        g.press("confirm", 4)
        g.wait_frames(14)
    st = cb.poll(g, lambda s: not s.dialog_open and s.control, 6.0, "control back after the talk")
    return st is not None


def press_rec(g, ctx: Ctx, leg: str, fid: int, entry: int) -> dict:
    """The state a press is judged from (settled): position, in_quad, control, the guestlocal block, a log mark."""
    st = rest(g, 3.0)
    p = pos(st)
    poly = GEOM[fid]["regions"][entry]
    return {"leg": leg, "field": fid, "entry": entry, "before": p, "p": p, "control": control(st),
            "in_quad": p is not None and in_quad(p[0], p[2], poly), "b0": gl(st), "at": cb.mark(g),
            "line_needed": FIRST_DECLINE.get(leg) == fid, "has_key": ctx.has_key}


def _stamp(samples, t0: float) -> list:
    out = []
    for s in samples:
        d = dict(cb.raw(s))
        d["_t"] = float(getattr(s, "read_at", t0) or t0) - t0
        out.append(d)
    return out


def _window(rec: dict, samples) -> None:
    within = [s for s in samples if s.get("_t", 0.0) <= HOLD_S + 0.05]
    rec["win"] = press_window(within, rec["before"])


def _close_rec(g, rec: dict) -> None:
    st = g.state
    rec["b1"] = gl(st)
    rec["d"] = counters_delta(rec.get("b0"), rec["b1"])
    rec["seq_moved"] = seq_moved(rec.get("b0"), rec["b1"])
    rec["lines"] = cb.new(g, rec["at"])
    rec["line"] = cb.count(rec["lines"], DECLINE_LINE.format(f=rec["field"])) > 0


def press_and_stay(g, ctx: Ctx, leg: str, fid: int, entry: int) -> dict:
    """ONE Confirm, then HOLD_S of publishes with NOTHING held -- a decline leg (D114 S114 M114 H114)."""
    rec = press_rec(g, ctx, leg, fid, entry)
    t0 = time.time()
    g.press("confirm", 2)
    samples = _stamp(cb.hold_for(g, HOLD_S), t0)
    _window(rec, samples)
    rec["samples"] = samples
    _close_rec(g, rec)
    if any(not control(s) for s in samples):
        recover(g, fid)                                  # a wrong engine climbed: put the player back, never hold blind
    return rec


def climb_hold(g, spec: dict, direction: str, t0: float | None = None) -> dict:
    """Hold the climb direction from a SEEN mount; release once y crossed the .eb's exit bound -- in try/finally, so a
    raise never leaves a key down. {"crossed", "samples"} (raw, _t from ``t0``: the press)."""
    button = spec["buttons"][direction]
    t0 = time.time() if t0 is None else t0
    out = {"crossed": False, "samples": []}
    g.hold(button, CLIMB_HOLD_FRAMES)
    try:
        samples, hit = cb.watch(g, lambda s: crossed((pos(s) or (0, None, 0))[1], spec, direction) or control(s)
                                or field_of(s) != spec["field"], CLIMB_S)
        out["samples"] = _stamp(samples, t0)
        out["crossed"] = hit is not None and crossed((pos(hit) or (0, None, 0))[1], spec, direction)
    finally:
        try:
            g.release(button)
        except HarnessError:
            pass
    return out


def _land(g, res: dict, t0: float, timeout: float) -> None:
    """Every publish until control comes back (the landing sample's `held` block is judged) -- on a talk leg, or the
    relayed talk's window opening at the landing (see landing_part)."""
    talk = res.get("talk_leg") is True
    samples, hit = cb.watch(g, lambda s: control(s) or (talk and dialog_open(s)), timeout)
    res["samples"] = (res.get("samples") or []) + _stamp(samples, t0)
    res["land"] = dict(cb.raw(hit)) if hit is not None else None
    res["last_pos"] = pos(samples[-1]) if samples else None
    res["land_at"] = time.time()


def _ended_poll(g, ctx: Ctx, res: dict, act: bool) -> None:
    """s156, an act leg: ended +1 and in_flight false within ENDED_POLL_S of control (D6: the flight ends on control and
    the body's frame and Seqs done -- an upper bound: 207's Seqs close BEFORE control, measured). Every publish of the
    poll is KEPT (res["after"], `_t` from the landing) with when the end was read (res["ended_after_s"]); WHEN the flight
    ended before control is flight_outlived's, over res["samples"]."""
    if not (ctx.has_key and act):
        res["b1"] = gl(g.state)
        return
    e0 = gl_get(res.get("b0"), "ended", int)
    t0 = res.get("land_at") or time.time()
    samples, hit = cb.watch(g, lambda s: gl_get(gl(s), "ended", int) == (e0 or 0) + 1
                            and gl_get(gl(s), "in_flight") is False, ENDED_POLL_S)
    res["after"] = _stamp(samples, t0)
    res["ended_ok"] = hit is not None and e0 is not None
    res["ended_after_s"] = res["after"][-1]["_t"] if hit is not None and res["after"] else None
    res["b1"] = gl(hit if hit is not None else g.state)


def ladder_run(g, ctx: Ctx, leg: str, fid: int, direction: str, *, act: bool, on_mount=None, talk: bool = False) -> dict:
    """press -> a MOUNT seen (never a key before it: THE ORDERING LAW 4) -> ``on_mount(g, res)`` (a mid-climb leg's
    business, no key held) -> hold, release at the exit bound -> the landing -> (s156, act) the ended poll."""
    spec = LADDERS[fid]
    entry = spec["entry_up"] if direction == "up" else spec["entry_down"]
    mount = spec["mount_bottom"] if direction == "up" else spec["mount_top"]
    res = press_rec(g, ctx, leg, fid, entry)
    res["talk_leg"] = talk
    t0 = time.time()
    g.press("confirm", 2)
    samples, hit = cb.watch(g, lambda s: is_mounted(s, mount), MOUNT_S)
    res["samples"] = _stamp(samples, t0)
    _window(res, res["samples"])
    res["mounted"] = hit is not None
    if not res["mounted"]:
        _close_rec(g, res)
        if not control(g.state):
            recover(g, fid)
        return res
    res["mount_at"] = time.time()
    if on_mount is not None:
        on_mount(g, res)
    c = climb_hold(g, spec, direction, t0)
    res["crossed"] = c["crossed"]
    res["samples"] += c["samples"]
    _land(g, res, t0, LAND_S)
    res["lines_at_land"] = cb.new(g, res["at"])        # the log as it stood at control (evidence; the talk legs judge ORDER)
    _ended_poll(g, ctx, res, act)
    res["d"] = counters_delta(res.get("b0"), res.get("b1"))
    res["seq_moved"] = seq_moved(res.get("b0"), res.get("b1"))
    res["lines"] = cb.new(g, res["at"])
    res["line"] = cb.count(res["lines"], DECLINE_LINE.format(f=fid)) > 0
    return res


def hop_run(g, ctx: Ctx, leg: str, hop: dict, *, act: bool) -> dict:
    """press with NO key held (never at a hop) -> control off within 2 s -> the landing -> (s156, act) the ended poll."""
    fid = hop["field"]
    res = press_rec(g, ctx, leg, fid, hop["entry"])
    t0 = time.time()
    g.press("confirm", 2)
    samples, hit = cb.watch(g, lambda s: not control(s), max(HOP_OFF_S, HOLD_S))
    res["samples"] = _stamp(samples, t0)
    if hit is None:
        more = cb.hold_for(g, max(0.0, HOLD_S - (time.time() - t0)))
        res["samples"] += _stamp(more, t0)
    _window(res, res["samples"])
    res["left"] = hit is not None and (time.time() - t0) <= HOP_OFF_S + 0.5
    if hit is None:
        _close_rec(g, res)
        return res
    _land(g, res, t0, HOP_S)
    _ended_poll(g, ctx, res, act)
    res["d"] = counters_delta(res.get("b0"), res.get("b1"))
    res["seq_moved"] = seq_moved(res.get("b0"), res.get("b1"))
    res["lines"] = cb.new(g, res["at"])
    res["line"] = cb.count(res["lines"], DECLINE_LINE.format(f=fid)) > 0
    return res


def recover(g, fid: int) -> None:
    """After a wrong engine's unexpected climb or a raise: no key down, no window open, and -- if the player hangs on a
    ladder -- back DOWN its own way (the far end would strand a later leg's pose either way; a note says so).

    THE HOLD-ONLY-AFTER-A-MOUNT LAW: a direction is held only for a body control-off ON the ladder (on_ladder: its height
    range and its own x/z path) -- never at the foot, where a mount still coming (a TimedTurn, a slow handler) would carry
    the held key into the mount. Such a body is waited for (up to LAND_S) until it mounts or control comes back; a late
    mount is then climbed out from the loop."""
    _release_all(g)
    try:
        st = g.state
        if st.dialog_open:
            close_line(g)
            return
        spec = LADDERS.get(fid)
        if spec is not None and not control(st):
            st = cb.poll(g, lambda s: control(s) or on_ladder(pos(s), spec), LAND_S,
                         f"control back or the body on {fid}'s ladder") or g.state
            p = pos(st)
            if not control(st) and on_ladder(p, spec):
                mount_b = dist3(p, spec["mount_bottom"]) <= dist3(p, spec["mount_top"])
                direction = "down" if mount_b else "up"
                g.note(f"recovery: the player hangs on {fid}'s ladder at {_fmt(p)} -- holding {direction} to its own end")
                c = climb_hold(g, spec, direction)
                cb.poll(g, lambda s: s.control, LAND_S, "control after the recovery climb")
                g.note(f"recovery climb: crossed {c['crossed']}")
            elif not control(st):
                g.note(f"recovery: control off at {_fmt(p)}, NOT on {fid}'s ladder ({path_dist(p, spec):.0f} u off its "
                       f"path) -- no direction held, waiting for control")
        cb.poll(g, lambda s: s.control, LAND_S, "control after the recovery")
    except HarnessError as err:
        g.note(f"recovery: {str(err)[:200]}")


def floor_of(x, fid: int) -> str | None:
    p = pos(x)
    if p is None:
        return None
    if fid in LADDERS:
        return "top" if p[1] < LADDERS[fid]["split_y"] else "bottom"
    if p[1] < -340:
        return "shelf"
    return "ledge" if p[1] < -150 else "ground"


def ensure_pose(g, ctx: Ctx, leg: str, fid: int, pose: str) -> tuple:
    """The leg's start pose, reached by the previous leg or a bench-0 STOCK repositioning climb / hop (THE ORDERING LAW
    8: a note, never a check). (ok, why)."""
    st = rest(g)
    fl = floor_of(st, fid)
    if fid in LADDERS:
        spec = LADDERS[fid]
        want_region = GEOM[fid]["regions"][spec["entry_up"] if pose == "bottom" else spec["entry_down"]]
        if fl != pose:
            # the stock press needs the FAR end's press region (114: e9 both ends; 207: e11 bottom, e10 top)
            src_stand, src_entry = ((spec["stand_bottom"], spec["entry_up"]) if pose == "top"
                                    else (spec["stand_top"], spec["entry_down"]))
            p = pos(st)
            if p is None or not in_quad(p[0], p[2], GEOM[fid]["regions"][src_entry]):
                ok, why = go_to(g, fid, src_stand, GEOM[fid]["regions"][src_entry])
                if not ok:
                    return False, f"the reposition could not reach its press region: {why}"
            ok, why = stock_move(g, ctx, leg, fid, "up" if pose == "top" else "down")
            if not ok:
                return False, why
        p = pos(rest(g))
        if p is None or not in_quad(p[0], p[2], want_region):
            ok, why = go_to(g, fid, spec["stand_bottom"] if pose == "bottom" else spec["stand_top"], want_region)
            if not ok:
                return False, why
        return True, ""
    if pose == "shelf":
        if fl != "shelf":
            ok, why = ensure_pose(g, ctx, leg, fid, "ledge")
            if not ok:
                return False, why
            ok, why = stock_move(g, ctx, leg, fid, "out")
            if not ok:
                return False, why
        p = pos(rest(g))
        return (p is not None and in_quad(p[0], p[2], GEOM[408]["regions"][5])), f"on the shelf at {_fmt(p)}"
    if fl == "shelf":
        ok, why = stock_move(g, ctx, leg, fid, "ret")
        if not ok:
            return False, why
    p = pos(rest(g))
    if p is None or not in_quad(p[0], p[2], GEOM[408]["regions"][4]) or not p[1] > HOPS["out"]["band"][0]:
        return go_to(g, fid, HOPS["out"]["stand"], GEOM[408]["regions"][4])
    return True, ""


def stock_move(g, ctx: Ctx, leg: str, fid: int, way: str) -> tuple:
    """A bench-0 STOCK climb / hop to reposition (a note)."""
    ok, why = set_bench(g, False)
    if not ok:
        return False, f"the reposition's `bench 0` failed: {why}"
    if fid in LADDERS:
        res = ladder_run(g, ctx, f"{leg}:reposition", fid, way, act=False)
        land = LADDERS[fid]["land_top"] if way == "up" else LADDERS[fid]["land_bottom"]
    else:
        res = hop_run(g, ctx, f"{leg}:reposition", HOPS[way], act=False)
        land = HOPS[way]["land"]
    landed = res.get("land") is not None and landed_at(res["land"], land)
    g.note(f"reposition for {leg}: a bench-0 stock {'climb ' + way if fid in LADDERS else 'hop ' + way} on {fid} "
           f"(a note, not a check) -> {'landed' if landed else 'DID NOT LAND'} at {_fmt(pos(res['land'])) if res.get('land') else 'none'}")
    return landed, "" if landed else f"the bench-0 reposition {way} on {fid} did not land ({_win(res.get('win'))})"


def arrive(g, ctx: Ctx, led: cb.Ledger, fid: int, *, scenario: int | None = None) -> tuple:
    """warp(fid, entrance 0) (never -1: 408's debug party reset), the post-init witness, then K3 (UNDRESSED).

    THE ENV-SLOT LAW (found by the s155 calibration): 408's and 207's Main_Init turn an env-sound slot byte still 2
    (``Global.Byte[13]`` / ``[14]``: playing) into 9 and raise the stock debug window "Error Env Play() / Slot=N", then
    WaitWindow on it -- control never comes. 114 leaves slot 1 at 2, and a debug warp skips the exit cleanup a real
    door runs, so both slots are zeroed just before the warp (a note, not a check)."""
    try:
        g.poke(13, 0)
        g.poke(14, 0)
        g.note(f"warp {fid}: env-sound slots Global.Byte[13]/[14] zeroed first (the debug warp skips the exit's cleanup)")
    except (HarnessError, AttributeError) as err:
        g.note(f"warp {fid}: the env-slot poke refused ({str(err)[:120]}) -- the field may raise 'Error Env Play()'")
    try:
        g.warp(fid, entrance=0, scenario=scenario)
    except HarnessError as err:
        return False, f"warp {fid} failed: {str(err)[:200]}"
    st = cb.poll(g, lambda s: arrived(s, fid)[0], 15.0, f"field {fid}'s post-init witness")
    ok, why = arrived(st or g.state, fid)
    if not ok:
        return False, f"no post-init witness on {fid}: {why}"
    undress(g, ctx, led, fid)
    return True, why


def undress(g, ctx: Ctx, led: cb.Ledger, fid: int) -> None:
    st = g.state
    if cb.path(st, "netsync.dress.self.armed") is True:
        ok, why = _ns(g, "selfdress", "self", "off")
        g.note(f"K3: dress.self.armed was true on {fid} -- `netsync selfdress self off` {'taken' if ok else 'REFUSED: ' + why}")
        st = cb.poll(g, lambda s: cb.path(s, "netsync.dress.self.armed") is False, 3.0, "the self dress off") or g.state
    ok, why = undressed(st, fid)
    if not ctx.dress_noted:
        g.note("UNDRESSED guest: the field's own player model climbs, with its own ladder and jump clips (owner decision 4 "
               "/ critique fix 8) -- Vivi on 114, Zidane on 408 and 207")
        ctx.dress_noted = True
    ctx.k3.append((fid, ok, why))
    if not ok:
        g.note(f"K3 RED at the {fid} arrival: {why}")


# ================================================================================================ the run
def run(g, field: int | None = None):
    calibrate = cb.CALIBRATE
    st0 = cb.poll(g, lambda s: s.netsync is not None, 15.0, "the netsync block (protocol 5)") or g.state
    has_key = cb.has(st0, PROBE)
    ctx = Ctx(mode_of(calibrate, has_key), has_key)
    led = cb.Ledger(g, catalog(calibrate, has_key), finals=FINALS, width=LEDGER_WIDTH)
    if field is not None:
        g.note(f"--field {field} is ignored: the bench picks its own fields (114 -> 408 -> 207)")
    g.note(f"s156 guest traversal, solo, mode {ctx.mode!r} ({'COOP_CALIBRATE=1' if calibrate else 'plain'}; "
           f"`netsync.guestlocal` {'published' if has_key else 'ABSENT: the s155 calibration, automatic'}); expected "
           f"{'%d/%d' % tally(ctx.mode)}")
    if not has_key:
        g.note("s155: N/A legs dropped from the catalog, never scored: " + ", ".join(NA_S155))
    try:
        ctx.k0_ok = _k0(g, ctx, led)
        if not ctx.k0_ok:
            led.close("not reached: K0 (the setup or a preflight) refused")
            return
        _k1_k2(g, ctx, led)
        if ctx.mode == "lever":
            ok, why = gl_op(g, ctx, "off")
            st = cb.poll(g, lambda s: gl_get(gl(s), "lever") == "off", 3.0, "the off lever read back")
            ctx.lever_held = ok and st is not None
            g.note(f"CALIBRATION: `guestlocal off` {'taken' if ok else 'REFUSED: ' + why}, held for the whole run (no leg "
                   f"sends act / shadow / clear / mutate; D114 re-asserts off); predicted red {', '.join(PREDICTED_OFF)}")
        _field_114(g, ctx, led)
        _field_408(g, ctx, led)
        _field_207(g, ctx, led)
    except HarnessError as err:
        g.note(f"the run raised: {str(err)[:400]}")
        led.close(f"not reached: the run raised ({str(err)[:200]})")
    finally:
        _release_all(g)
        if ctx.k3:
            led.check("K3", len(ctx.k3) == 3 and all(ok for _, ok, _ in ctx.k3), "; ".join(w for _, _, w in ctx.k3)
                      + f" ({len(ctx.k3)} of 3 arrivals)" + ("" if len(ctx.k3) == 3 else " -- the run ended first"))
        else:
            led.unreached(["K3"], "no field was arrived at")
        if "K-TRIPS" in led.catalog and "K-TRIPS" not in led.done and ctx.trips0 is None:
            led.unreached(["K-TRIPS"], "K2 never read trips.total (the run ended first)")
        if "K-TRIPS" in led.catalog and "K-TRIPS" not in led.done:
            t1 = gl_get(gl(g.state), "trips.total", int)
            led.check("K-TRIPS", t1 is not None and t1 == ctx.trips0,
                      f"trips.total {ctx.trips0!r} at K2 -> {t1!r} after the last leg (no false trips: the selftest's op / "
                      f"who rows back the classifier); last trip {gl_get(gl(g.state), 'trips.last')!r}")
        if ctx.k0_ok:
            _k_r(g, ctx, led)
        else:
            if not getattr(g, "attach", False):
                try:
                    cb.release(g)                              # a refused preflight may already hold the role: let it go
                except HarnessError as err:
                    g.note(f"the release after K0's refusal: {str(err)[:200]}")
            led.unreached(["K-R"], "K0 refused: the bench never ran a leg (the role, if taken, released unjudged)")
        g.note(f"Memoria.log archived: {cb.archive_log(g, 'guest-traversal-' + ctx.mode)}")
        if ctx.mode != "plain":
            led.close("not reached: the run ended before this check")
            ok, why = judge_markers(ctx.mode, ctx.marks)
            led.check("K-CAL-M", ok, why)
            led.judge_calibration("K-CAL", predicted(ctx.mode))
        led.close(final=True)


