def line_rx(template: str, **known) -> re.Pattern:
    """A log-line regex from a template: known {names} literal, the rest non-greedy."""
    out = []
    for piece in re.split(r"(\{\w+\})", template):
        m = re.fullmatch(r"\{(\w+)\}", piece)
        if m:
            out.append(re.escape(str(known[m.group(1)])) if m.group(1) in known else r".+?")
        elif piece:
            out.append(re.escape(piece))
    return re.compile("".join(out))


def literal_pieces(template: str, min_len: int = 6) -> list:
    """The literal runs between a template's {placeholders} -- what the engine source must carry verbatim."""
    return [p for p in re.split(r"\{\w+\}", template) if len(p.strip()) >= min_len]


_CS_LITERAL = re.compile(r'''(?<![@$\w'])"((?:[^"\\\n]|\\.)*)"''')   # not verbatim / interpolated, not the char '"'


def cs_literals(text: str) -> list:
    r"""The C# string literals of ``text``, in order, unescaped (\" and \\ only: the engine's log texts use no other)."""
    return [m.group(1).replace('\\"', '"').replace("\\\\", "\\") for m in _CS_LITERAL.finditer(text)]


def spelled(piece: str, lits: list, window: int = 16) -> bool:
    """Do the literals ``lits``, IN ORDER, spell ``piece`` -- a suffix of one, whole ones, a prefix of the last, with any
    expressions or other literals (a ternary's alternatives, a format argument) between them, inside ``window`` literals?
    A word that drifted in the engine's text is never spelled."""
    def rest_from(rest: str, j0: int, jmax: int) -> bool:
        if not rest:
            return True
        for j in range(j0, min(jmax, len(lits))):
            b = lits[j]
            if b and b.startswith(rest):
                return True
            if b and rest.startswith(b) and rest_from(rest[len(b):], j + 1, jmax):
                return True
        return False
    for i, a in enumerate(lits):
        if piece in a:
            return True
        for k in range(len(a)):
            suf = a[k:]
            if piece.startswith(suf) and rest_from(piece[len(suf):], i + 1, i + 1 + window):
                return True
    return False


def _parts(parts) -> str:
    return ", ".join(f"{n} {'yes' if v else 'NO'}" for n, v in parts)


def _win(win) -> str:
    if not isinstance(win, dict):
        return "no press window"
    return f"{win.get('n')} samples, control fell {win.get('fell')}, max |d| {win.get('max_d')}"


def _fmt(p) -> str:
    return "none" if p is None else "(" + ", ".join(f"{v:.0f}" for v in p) + ")"


