def _talk_climb(g, ctx, led, leg: str, direction: str, pose: str, *, scene: bool = False, hang_s: float = 0.0):
    """A talk leg's climb (114, JJY): mounted -> [`hostscene 1`] -> `netsync talk 3`, with NO key held -> [a hang] -> the
    climb. The log is split at the landing (a start logged BEFORE control came back started MID-climb), then JJY's start
    is waited for. res["talk"]: sent, why, at (the log mark at the send), lines_mid, early, started_s (after control)."""
    if not _pose_or_skip(g, ctx, led, leg, 114, pose):
        return None
    ok, why = set_bench(g, True)
    if not ok:
        led.unreached([leg], f"`bench 1` failed: {why}")
        return None
    talk = {"sent": False, "why": "", "early": False, "started_s": None, "lines_mid": []}

    def on_mount(gg, res):
        sent = [_ns(gg, "hostscene", 1)] if scene else []
        talk["at"] = cb.mark(gg)
        talk["in_flight_at_send"] = gl_get(gl(gg.state), "in_flight")
        sent.append(_ns(gg, "talk", JJY_UID))
        talk["sent"] = all(ok for ok, _ in sent)
        talk["why"] = "; ".join(w for ok, w in sent if not ok)
        if hang_s > 0:
            t0 = time.time()
            res["hang"] = _stamp(cb.hold_for(gg, hang_s), t0)
        res["hang_s"] = time.time() - res["mount_at"]

    res = ladder_run(g, ctx, leg, 114, direction, act=True, on_mount=on_mount, talk=True)
    _mark(ctx, leg, res)
    res["talk"] = talk
    if not res.get("mounted") or "at" not in talk:
        return res
    started = TALK_STARTED.format(u=JJY_UID, f=114)
    lines = cb.wait_log(g, talk["at"], started, TALK_START_S + 0.5)
    if cb.count(lines, started):
        talk["started_s"] = time.time() - (res.get("land_at") or time.time())
    # THE ORDER LAW of the log: the gate logs its "climb ended" (L3) before a held start can apply (TalkDeferWhy defers
    # while in flight; C5 samples the flight before ServiceTalkFollow) -- a start logged before L3 started MID-climb.
    # (Never the publish at the landing: the start can take control in the very frame the climb hands it back.)
    ended_rx = line_rx(GL_ENDED, f=114, e=9)
    i_end = next((i for i, ln in enumerate(lines) if ended_rx.search(ln)), None)
    i_start = next((i for i, ln in enumerate(lines) if started in ln), None)
    talk["early"] = i_start is not None and (i_end is None or i_start < i_end)
    talk["lines_mid"] = lines[:i_end] if i_end is not None else list(lines)
    talk["ended_line"] = i_end is not None
    cb.hold_for(g, 0.25)                                 # the counters the start moved (NoteTalkResult) publish
    res["b1"] = gl(g.state)
    res["d"] = counters_delta(res.get("b0"), res["b1"])
    res["lines"] = cb.new(g, res["at"])
    return res


