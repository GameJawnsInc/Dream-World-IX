def offset_from(lines, ini=None) -> tuple:
    """The selftest snap offset: the engine's LAST config line (it prints ' selfTestOffset=dx,dz' only when the offset is
    not 250,0, so a config line without it IS 250,0); with no config line at all, the root's ini [Netsync] SelfTestOffset
    read-only; else the default. (dx, dz, source)."""
    for ln in reversed(list(lines or ())):
        if "[NetSync] config enabled=" in ln:
            m = CONFIG_OFFSET_RX.search(ln)
            if m:
                return int(m.group(1)), int(m.group(2)), "the engine's config line"
            return 250, 0, "the engine's config line (the default: no selfTestOffset token)"
    if ini:
        m = re.fullmatch(r"\s*(-?\d+)\s*,\s*(-?\d+)\s*", str(ini))
        if m:
            return int(m.group(1)), int(m.group(2)), "the ini (read-only)"
    return 250, 0, "the default (no line, no ini value)"


