def dist3(a, b) -> float:
    if a is None or b is None:
        return math.inf
    return math.sqrt(sum((float(p) - float(q)) ** 2 for p, q in zip(a, b)))


def dist_xz(a, b) -> float:
    """a, b: (x, y, z) or (x, z) -- the x/z distance."""
    if a is None or b is None:
        return math.inf
    ax, az = (a[0], a[2]) if len(a) == 3 else (a[0], a[1])
    bx, bz = (b[0], b[2]) if len(b) == 3 else (b[0], b[1])
    return math.hypot(float(ax) - float(bx), float(az) - float(bz))


def near(p, target, xz: float = XZ_TOL, y: float = Y_TOL) -> bool:
    return (p is not None and abs(p[0] - target[0]) <= xz and abs(p[2] - target[2]) <= xz
            and abs(p[1] - target[1]) <= y)


def _in_tri(x: float, z: float, a, b, c) -> bool:
    """Math3D.PointInsideTriangleTest with largeBorder (Math3D.cs:28-43) on XZ: barycentric, border-inclusive to
    u + v <= 1.000001; a degenerate triangle contains nothing (the engine's 1 / 0 makes NaN)."""
    acx, acz = float(c[0]) - a[0], float(c[1]) - a[1]
    abx, abz = float(b[0]) - a[0], float(b[1]) - a[1]
    apx, apz = x - a[0], z - a[1]
    cross = acx * abz - acz * abx
    if cross == 0:
        return False
    acsq, acab, acap = acx * acx + acz * acz, acx * abx + acz * abz, acx * apx + acz * apz
    absq, abap = abx * abx + abz * abz, abx * apx + abz * apz
    den = cross * cross
    u = (absq * acap - acab * abap) / den
    v = (acsq * abap - acab * acap) / den
    return u >= 0.0 and v >= 0.0 and u + v <= 1.000001


def in_quad(x: float, z: float, poly) -> bool:
    """EventEngine.TreadQuad.cs IsInQuad's twin: the n triangles (q[i], q[i+1 mod n], q[i+2 mod n]) -- a FAN OF TRIPLETS,
    x/z only (TreadQuad never reads the height: 114 e9 covers both ladder ends)."""
    pts = [(float(p[0]), float(p[1])) for p in poly]
    n = len(pts)
    return n >= 3 and any(_in_tri(float(x), float(z), pts[i % n], pts[(i + 1) % n], pts[(i + 2) % n]) for i in range(n))


