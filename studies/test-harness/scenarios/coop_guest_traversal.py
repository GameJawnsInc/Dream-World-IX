def flight_outlived(samples, field: int, entry: int, land, e0=None) -> tuple:
    """WHEN the flight ended (an act leg): it must outlive the climb. FlightRule lands only with control BACK (and Bails only
    before control ever fell), so on a correct engine every publish from the arm to the landing reads in flight on (field,
    entry) and `ended` stays at ``e0`` (the pre-press read). The landing is the first publish after control fell that is
    at ``land`` (+-48 x/z, +-32 y), has control back, or shows a window -- cut at the position too, because a relayed talk
    can take control in the very frame the climb hands it back (T114-MID / T114-HANG). The last control-off publish before
    it is named on its own (the one an early end reads first). (ok, why)."""
    samples = list(samples or ())
    i_off = next((i for i, s in enumerate(samples) if not control(s) and not dialog_open(s)), None)
    if i_off is None:
        return False, "control never fell"
    i_land = next((i for i in range(i_off, len(samples)) if (land is not None and near(pos(samples[i]), land))
                   or control(samples[i]) or dialog_open(samples[i])), len(samples))
    i0 = next((i for i in range(i_land) if _flying(samples[i], field, entry)), None)
    if i0 is None:
        return False, f"no publish in flight on ({field}, {entry}) before the landing"
    off = [s for s in samples[i0:i_land] if not _flying(s, field, entry)]
    moved = [s for s in samples[:i_land] if e0 is not None and gl_get(gl(s), "ended", int) not in (None, e0)]
    last = next((s for s in reversed(samples[:i_land]) if not control(s)), None)
    last_ok = last is not None and _flying(last, field, entry)
    ok = not off and not moved and last_ok
    return ok, (f"{i_land - i0} publishes from the arm to the landing, {len(off)} off the flight"
                + (f" (first at {_fmt(pos(off[0]))})" if off else "") + f", ended moved on {len(moved)}; the last "
                f"control-off publish before the landing {'in flight' if last_ok else 'NOT in flight'} at "
                f"{_fmt(pos(last)) if last is not None else 'none'}")


