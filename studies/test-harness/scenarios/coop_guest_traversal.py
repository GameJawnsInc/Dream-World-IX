def judge_ladder(res, spec: dict, direction: str, *, act: bool, has_key: bool) -> tuple:
    """One climb: the BEHAVIOUR (mounted, the bound crossed, the landing, mid-ladder control-off samples ON the ladder's
    path -- a climb, not a teleport) and, on s156, the gate's half: a positive control leaves every counter alone; an act
    climb is allowed once, flies on (field, entry) until its landing, ends after control (never bailed, never aborted)
    and trips nothing."""
    entry = spec["entry_up"] if direction == "up" else spec["entry_down"]
    land = spec["land_top"] if direction == "up" else spec["land_bottom"]
    parts, why = [], []
    if not res.get("mounted"):
        return False, f"no mount within {MOUNT_S:g} s of the press ({_win(res.get('win'))}; {res.get('why') or ''})"
    l_ok, contaminated, l_why = landing_part(res, land)
